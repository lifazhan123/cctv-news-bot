import os

from scrapy.crawler import CrawlerProcess

from analyzer.filter import analyze_news
from analyzer.score import calculate_score


# ==========================================================
# 全局新闻结果
# ==========================================================

results = []


# ==========================================================
# Scrapy Pipeline
# ==========================================================

class CollectingPipeline:

    def process_item(self, item, spider):

        results.append(dict(item))

        return item


# ==========================================================
# 新闻分析
# ==========================================================

def process_stock_news(news_list):

    processed = []

    for news in news_list:

        # --------------------------------------------------
        # 1. 股票/行业匹配
        # --------------------------------------------------

        news = analyze_news(news)

        # --------------------------------------------------
        # 2. 新闻评分
        # --------------------------------------------------

        news = calculate_score(news)

        # --------------------------------------------------
        # 3. 进入邮件的核心规则
        #
        # 只要满足以下任意一个条件：
        #
        #   A. 出现关注股票名称/代码
        #   B. 出现关注行业关键词
        #
        # 就进入邮件。
        #
        # 不再判断：
        #   - 是否重大行业新闻
        #   - 是否政策新闻
        #   - 是否宏观新闻
        # --------------------------------------------------

        if (
            news.get("matched_stocks")
            or news.get("matched_industries")
        ):

            processed.append(news)

    return processed


# ==========================================================
# 主程序
# ==========================================================

def main():

    # ======================================================
    # Scrapy 配置
    # ======================================================

    process = CrawlerProcess({

        "USER_AGENT": (
            "Mozilla/5.0 (Windows NT 10.0; Win64; x64) "
            "AppleWebKit/537.36 "
            "(KHTML, like Gecko) "
            "Chrome/153.0.0.0 Safari/537.36"
        ),

        # 不遵守 robots.txt
        "ROBOTSTXT_OBEY": False,

        # 请求间隔
        "DOWNLOAD_DELAY": 1,

        # 并发请求数量
        "CONCURRENT_REQUESTS": 2,

        # ==================================================
        # 注意：
        #
        # 这里必须使用 __main__.CollectingPipeline
        #
        # 不能写成：
        # main.CollectingPipeline
        #
        # 否则 python main.py 运行时可能出现：
        #
        # item_scraped_count 有数据
        # 但 results 最后还是 0
        # ==================================================

        "ITEM_PIPELINES": {
            "__main__.CollectingPipeline": 300
        },

        # 日志级别
        "LOG_LEVEL": "INFO",

        # Scrapy 请求指纹
        "REQUEST_FINGERPRINTER_IMPLEMENTATION": "2.7",
    })


    # ======================================================
    # 第一部分：抓取央视新闻
    # ======================================================

    print()

    print("=" * 60)
    print("开始抓取央视新闻")
    print("=" * 60)


    # ------------------------------------------------------
    # CCTV-1
    # ------------------------------------------------------

    from crawler.cctv1 import Cctv1Spider

    process.crawl(Cctv1Spider)


    # ------------------------------------------------------
    # CCTV-2
    # ------------------------------------------------------

    from crawler.cctv2 import Cctv2Spider

    process.crawl(Cctv2Spider)


    # ------------------------------------------------------
    # CCTV-13
    # ------------------------------------------------------

    from crawler.cctv13 import Cctv13Spider

    process.crawl(Cctv13Spider)


    # ======================================================
    # 第二部分：抓取股票相关新闻
    # ======================================================

    print()

    print("=" * 60)
    print("开始抓取股票相关新闻")
    print("=" * 60)


    from crawler.stock_news import StockNewsSpider

    process.crawl(StockNewsSpider)


    # ======================================================
    # 启动所有 Spider
    # ======================================================

    process.start()


    # ======================================================
    # 抓取结束
    # ======================================================

    print()

    print("=" * 60)
    print("全部新闻抓取完成")
    print("=" * 60)

    print(f"总共抓取：{len(results)} 条新闻")


    # ======================================================
    # 没有抓到任何新闻
    # ======================================================

    if not results:

        print()

        print("❌ 没有抓取到任何新闻")

        return


    # ======================================================
    # 开始分析
    # ======================================================

    print()

    print("=" * 60)
    print("开始分析股票及行业信息")
    print("=" * 60)


    stock_news = process_stock_news(results)


    print(
        f"股票/行业相关信息：{len(stock_news)} 条"
    )


    # ======================================================
    # 按评分从高到低排序
    # ======================================================

    stock_news.sort(
        key=lambda x: x.get("score", 0),
        reverse=True
    )


    # ======================================================
    # 控制台显示分析结果
    # ======================================================

    print()

    print("=" * 60)
    print("今日重点股票/行业新闻")
    print("=" * 60)


    # ------------------------------------------------------
    # 最多显示20条
    # ------------------------------------------------------

    for index, news in enumerate(
        stock_news[:20],
        1
    ):

        print()

        print(
            f"【{index}】 "
            f"{news.get('level', '')}"
        )

        print(
            f"评分："
            f"{news.get('score', 0)}"
        )

        print(
            f"标题："
            f"{news.get('title', '')}"
        )


        # --------------------------------------------------
        # 股票
        # --------------------------------------------------

        matched_names = [

            item["name"]

            for item in news.get(
                "matched_stocks",
                []
            )

        ]


        if matched_names:

            print(
                "涉及股票："
                + "、".join(matched_names)
            )

        else:

            print("涉及股票：无")


        # --------------------------------------------------
        # 行业
        # --------------------------------------------------

        matched_industries = news.get(
            "matched_industries",
            []
        )


        if matched_industries:

            print(
                "涉及行业："
                + "、".join(matched_industries)
            )

        else:

            print("涉及行业：无")


        # --------------------------------------------------
        # 来源
        # --------------------------------------------------

        print(
            f"来源："
            f"{news.get('source', '')}"
        )


        # --------------------------------------------------
        # 链接
        # --------------------------------------------------

        print(
            f"链接："
            f"{news.get('link', '')}"
        )


        # --------------------------------------------------
        # 评分原因
        # --------------------------------------------------

        reasons = news.get(
            "score_reasons",
            []
        )


        if reasons:

            print(
                "关注原因："
                + "、".join(reasons)
            )


    # ======================================================
    # 没有匹配到股票/行业
    # ======================================================

    if not stock_news:

        print()

        print("=" * 60)
        print("今天没有发现与你关注股票/行业相关的新闻")
        print("=" * 60)

        return


    # ======================================================
    # 准备发送邮件
    # ======================================================

    print()

    print("=" * 60)
    print("准备发送邮件")
    print("=" * 60)


    # ======================================================
    # 从环境变量读取163邮箱配置
    # ======================================================

    sender = os.environ.get(
        "EMAIL_SENDER"
    )

    password = os.environ.get(
        "EMAIL_PASSWORD"
    )

    receiver = os.environ.get(
        "EMAIL_RECEIVER",
        sender
    )


    # ======================================================
    # 检查发件邮箱
    # ======================================================

    if not sender:

        print(
            "❌ 错误：没有设置 EMAIL_SENDER"
        )

        return


    # ======================================================
    # 检查邮箱授权码
    # ======================================================

    if not password:

        print(
            "❌ 错误：没有设置 EMAIL_PASSWORD"
        )

        return


    # ======================================================
    # 检查收件邮箱
    # ======================================================

    if not receiver:

        print(
            "❌ 错误：没有设置 EMAIL_RECEIVER"
        )

        return


    # ======================================================
    # 发送邮件
    # ======================================================

    try:

        from mailer import send_email


        send_email(
            stock_news,
            sender,
            password,
            receiver
        )


        print()

        print("=" * 60)
        print("✅ 股票新闻邮件发送完成")
        print("=" * 60)


    except Exception as e:

        print()

        print("=" * 60)
        print("❌ 邮件发送失败")
        print("=" * 60)

        print(
            f"错误信息：{e}"
        )


# ==========================================================
# 程序入口
# ==========================================================

if __name__ == "__main__":

    main()
